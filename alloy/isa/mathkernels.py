"""Vector math kernels returned as intrinsics: every function has a ``strict``, a ``relaxed`` and a ``fast``
program in abstract primitives (``mathkernels.toml``, generated by ``helpers/mathfit.py``), rendered per ISA and
dtype with the spellings of ``mathprims.toml``. An agent copies the C function into its loop and drops the call.

``strict`` returns libm's special values on every input: one cold branch sends special lanes to scalar libm; elsewhere
it holds its recorded ulp. ``relaxed`` has no branch and holds only under its contract (finite inputs in its range).
``fast`` is ``relaxed`` at a lower degree, and the rungs of :data:`RUNGS` lie between the two, so a tolerance picks
the cheapest kernel that meets it (:func:`cheapest`).
"""

import ast
import dataclasses
import functools
import math
import pathlib
import re
import tomllib

__all__ = [
    "ALIASES",
    "LADDER",
    "LEVELS",
    "RUNGS",
    "Grid",
    "Kernel",
    "Spelled",
    "cheapest",
    "functions",
    "kernel",
    "kernels_for",
    "ladder",
    "level_for",
    "libraries",
    "render",
    "spelled",
    "target_of",
]

LEVELS = ("strict", "relaxed", "fast")
#: The rungs between ``relaxed`` and ``fast``, most accurate first; a function has those whose degree differs.
RUNGS = ("mid3", "mid2", "mid1")
#: Every kernel name, most accurate first.
LADDER = ("strict", "relaxed", *RUNGS, "fast")

#: Other names an agent may use for a function.
ALIASES = {"ln": "log"}

PRIMS_PATH = pathlib.Path(__file__).with_name("mathprims.toml")
KERNELS_PATH = pathlib.Path(__file__).with_name("mathkernels.toml")

#: Primitive -> what it returns; every other primitive returns a float vector.
INT_OPS = frozenset({"toint", "bits", "iadd", "isub", "iand", "ior", "ixor", "ishl", "ishr"})
MASK_OPS = frozenset({"le", "lt", "eq", "mand", "mor"})
#: Primitives whose second operand stays a literal shift count.
SHIFTS = frozenset({"ishl", "ishr"})


@dataclasses.dataclass(slots=True, frozen=True)
class Grid:
    """One sampling range of a kernel's validation: uniform (``lin``), log-uniform on both signs (``log``), or
    log-uniform near multiples of pi/2 (``near``). ``ylo``/``yhi`` give the second operand's range."""

    lo: float
    hi: float
    kind: str
    ylo: float = 0.0
    yhi: float = 0.0


@dataclasses.dataclass(slots=True, frozen=True)
class Kernel:
    """One program. ``body`` is SSA in abstract primitives over ``args``; ``guard`` names the mask of lanes the
    vector path computes (empty = no branch). ``error_ulp`` and ``error_abs`` are measured on ``grids``."""

    fn: str
    dtype: str
    level: str
    args: tuple[str, ...]
    body: tuple[str, ...]
    result: str
    guard: str
    contract: str
    grids: tuple[Grid, ...]
    specials: tuple[float, ...]
    error_ulp: float
    error_abs: float

    @property
    def name(self) -> str:
        return f"alloy_{self.fn}_{self.dtype}_{self.level}"


@dataclasses.dataclass(slots=True, frozen=True)
class Spelled:
    """A kernel rendered for one ISA: the C function and the number of intrinsics it runs."""

    kernel: Kernel
    isa: str
    source: str
    intrinsics: int


@functools.lru_cache(maxsize=1, typed=True)
def load_kernels() -> dict[tuple[str, str, str], Kernel]:
    """Every kernel, keyed by ``(function, dtype, level)``."""
    with KERNELS_PATH.open("rb") as handle:
        data = tomllib.load(handle)
    out = {}
    for fn, dtypes in data.items():
        for dtype, levels in dtypes.items():
            for level, k in levels.items():
                grids = tuple(Grid(**grid) for grid in k["grids"])
                out[fn, dtype, level] = Kernel(
                    fn,
                    dtype,
                    level,
                    tuple(k["args"]),
                    tuple(k["body"]),
                    k["result"],
                    k.get("guard", ""),
                    k["contract"],
                    grids,
                    tuple(k.get("specials", ())),
                    k["error_ulp"],
                    k["error_abs"],
                )
    return out


@functools.lru_cache(maxsize=1, typed=True)
def load_prims() -> dict:
    with PRIMS_PATH.open("rb") as handle:
        return tomllib.load(handle)["prims"]


def functions() -> tuple[str, ...]:
    """The functions with kernels, in table order."""
    return tuple(dict.fromkeys(fn for fn, _, _ in load_kernels()))


def kernel(fn: str, dtype: str, level: str) -> Kernel:
    """The kernel of ``fn``, or ``KeyError`` naming what exists."""
    name = ALIASES.get(fn, fn)
    if name not in functions():
        raise KeyError(f"{fn!r}: no math kernel (one of: {', '.join(functions())}; ln = log)")
    if dtype not in ("f64", "f32"):
        raise KeyError(f"{fn}: math kernels cover f64 and f32, not {dtype!r}")
    if level not in LADDER:
        raise KeyError(f"{level!r}: no such level (one of: {', '.join(LADDER)})")
    found = load_kernels().get((name, dtype, level))
    if found is None:
        rungs = ", ".join(k.level for k in ladder(name, dtype))
        raise KeyError(f"{name} {dtype} has no {level} rung (it has: {rungs})")
    return found


def ladder(fn: str, dtype: str) -> tuple[Kernel, ...]:
    """Every kernel of ``fn``, most accurate level first."""
    name, kernels = ALIASES.get(fn, fn), load_kernels()
    return tuple(kernels[name, dtype, level] for level in LADDER if (name, dtype, level) in kernels)


def expand(template: str, fields: dict[str, str], args: tuple[str, ...] = ()) -> str:
    """``template`` with its ``${field}`` and ``$0`` holes filled."""
    text = re.sub(r"\$\{(\w+)\}", lambda m: fields[m.group(1)], template)
    return re.sub(r"\$(\d)", lambda m: args[int(m.group(1))], text)


def literal(value: float, dtype: str) -> str:
    """``value`` as a C literal of the lane type."""
    if math.isnan(value):
        return "NAN"
    if value in (float("inf"), float("-inf")):
        text = "INFINITY" if value > 0 else "-INFINITY"
        return text if dtype == "f32" else f"(double){text}"
    text = repr(float(value))
    return f"{text}f" if dtype == "f32" else text


class Renderer:
    """Spells one program for one ISA and dtype, counting the intrinsics it runs."""

    __slots__ = ("count", "dtype", "fields", "ops")

    def __init__(self, isa: str, dtype: str) -> None:
        table = load_prims()[isa]
        self.fields = table["fields"][dtype]
        self.ops = {**table["ops"], **table.get("overrides", {}).get(dtype, {})}
        self.dtype = dtype
        self.count = 0

    def call(self, op: str, *args: str) -> str:
        self.count += 1
        return expand(self.ops[op], self.fields, args)

    def constant(self, node: ast.Constant | ast.UnaryOp) -> str:
        operand = node.operand if isinstance(node, ast.UnaryOp) else node
        if not isinstance(operand, ast.Constant) or not isinstance(operand.value, int | float):
            raise ValueError(f"{ast.unparse(node)}: not a numeric literal")
        value = -operand.value if isinstance(node, ast.UnaryOp) else operand.value
        if isinstance(value, int):
            return self.call("seti", f"{value}LL" if self.dtype == "f64" else str(value))
        return self.call("set", literal(value, self.dtype))

    def expr(self, node: ast.expr) -> str:
        if isinstance(node, ast.Name):
            return node.id
        if isinstance(node, ast.Constant | ast.UnaryOp):
            return self.constant(node)
        if not isinstance(node, ast.Call):
            raise ValueError(f"{ast.unparse(node)}: not a primitive call")
        name = ast.unparse(node.func)
        if name == "set":
            return self.expr(node.args[0])
        if name == "horner":  # horner(t, c0, c1, ..., cn) = c0 + t*(c1 + t*(... + t*cn))
            point, *coefficients = node.args
            at = self.expr(point)
            value = self.expr(coefficients[-1])
            for coefficient in reversed(coefficients[:-1]):
                value = self.call("fma", value, at, self.expr(coefficient))
            return value
        if name in SHIFTS:
            return self.call(name, self.expr(node.args[0]), ast.unparse(node.args[1]))
        return self.call(name, *(self.expr(arg) for arg in node.args))

    def type_of(self, node: ast.expr) -> str:
        name = ast.unparse(node.func) if isinstance(node, ast.Call) else ""
        return self.fields["ivec" if name in INT_OPS else "mask" if name in MASK_OPS else "vec"]

    def statement(self, line: str) -> str:
        target, _, expression = line.partition(" = ")
        node = ast.parse(expression, mode="eval").body
        return f"    {self.type_of(node)} {target} = {self.expr(node)};"


def cold_path(k: Kernel, r: Renderer) -> list[str]:
    """Lanes outside the guard recompute through scalar libm; the only branch of a ``strict`` kernel."""
    c, n = r.fields["c"], r.fields["lanes"]
    # A scalable vector's lane count is no constant, and C++ takes no variable-length array.
    size = r.fields.get("max_lanes", n)
    arrays = ", ".join(f"{name}s[{size}]" for name in [*k.args, "v", "bad"])
    suffix = "f" if k.dtype == "f32" else ""
    call = ", ".join(f"{name}s[j]" for name in k.args)
    # exp10 needs _GNU_SOURCE, which a kernel cannot define after the file's first include.
    scalar = f"pow{suffix}({literal(10.0, k.dtype)}, {call})" if k.fn == "exp10" else f"{k.fn}{suffix}({call})"
    one, zero = r.call("set", literal(1.0, k.dtype)), r.call("set", literal(0.0, k.dtype))
    stores = [f"        {r.call('store', f'{name}s', name)};" for name in k.args]
    return [
        f"    if (__builtin_expect(!{r.call('allok', k.guard)}, 0)) {{",
        f"        {c} {arrays};",
        *stores,
        f"        {r.call('store', 'vs', k.result)};",
        f"        {r.call('store', 'bads', r.call('select', k.guard, zero, one))};",
        "        for (int j = 0; j < (int)" + n + "; j++)",
        f"            if (bads[j] != 0) vs[j] = {scalar};",
        f"        {k.result} = {r.call('load', 'vs')};",
        "    }",
    ]


#: The FP levels of ``configuration_matrix.toml`` that compile with reassociation on.
REASSOCIATING = frozenset({"reassoc", "fast"})

#: Reassociation undoes the compensation ``strict`` relies on, so gcc refuses such a translation unit, which it marks
#: with a macro, and clang, which does not, turns it off inside the function, a pragma that survives inlining.
#: ``relaxed`` and ``fast`` tolerate it at about twice the error, but for the functions of NEEDS_IEEE, whose every
#: level folds its correction term to zero.
NEEDS_IEEE = frozenset({"log1p"})


def refuse_reassociation(advice: str) -> tuple[str, ...]:
    """The preprocessor lines that refuse a reassociating translation unit."""
    return (
        "#if defined(__FAST_MATH__) || defined(__ASSOCIATIVE_MATH__)",
        f'#error "strict math kernels need IEEE semantics: drop -ffast-math here, or {advice}"',
        "#endif",
    )


#: The first lines of a kernel body that must not reassociate under clang.
NO_REASSOCIATION = ("#if defined(__clang__)", "#pragma clang fp reassociate(off)", "#endif")


def render(k: Kernel, isa: str) -> Spelled:
    """``k`` as a C function for ``isa``."""
    r = Renderer(isa, k.dtype)
    vec = r.fields["vec"]
    params = ", ".join(f"{vec} {name}" for name in k.args)
    refuses = k.level == "strict" or k.fn in NEEDS_IEEE
    advice = "call the library" if k.fn in NEEDS_IEEE else "use the relaxed kernel"
    lines = [*(refuse_reassociation(advice) if refuses else ()), f"static inline {vec} {k.name}({params}) {{"]
    lines += [*(NO_REASSOCIATION if refuses else ()), *(r.statement(line) for line in k.body)]
    if k.guard:
        lines += cold_path(k, r)
    lines += [f"    return {k.result};", "}"]
    return Spelled(k, isa, "\n".join(lines), r.count)


def level_for(fp_level: str, *, finite_inputs: bool) -> str:
    """The kernel a build at ``fp_level`` takes: ``strict`` unless the inputs are declared finite, and never under
    reassociation, where it does not compile. ``relaxed`` still needs the inputs in its range, which only the reader
    of its contract knows; ``fast`` trades digits, so only a person or an agent picks it."""
    return "relaxed" if finite_inputs or fp_level in REASSOCIATING else "strict"


def target_of(isa: str) -> str:
    """The primitive set of ``isa``: AVX-512 at 256 bits has no 256-bit set of its own and runs the AVX2 one."""
    return "avx2" if isa == "avx512_256" else isa


def spelled(fn: str, dtype: str, level: str, isa: str) -> Spelled:
    return render(kernel(fn, dtype, level), target_of(isa))


def kernels_for(fn: str, dtype: str, isa: str) -> tuple[Spelled, ...]:
    """The strict, relaxed and fast kernels of ``fn``."""
    return tuple(spelled(fn, dtype, level, isa) for level in LEVELS)


def cheapest(fn: str, dtype: str, isa: str, *, max_ulp: float | None = None, max_abs: float | None = None) -> Spelled:
    """The kernel of ``fn`` with the fewest intrinsics whose recorded error holds both bounds, or ``KeyError`` naming
    the most accurate one there is."""
    rungs = ladder(fn, dtype)
    if not rungs:
        kernel(fn, dtype, LEVELS[0])
    holds = [
        k for k in rungs if (max_ulp is None or k.error_ulp <= max_ulp) and (max_abs is None or k.error_abs <= max_abs)
    ]
    if not holds:
        best = min(rungs, key=lambda k: k.error_ulp)
        raise KeyError(
            f"{fn} {dtype}: no kernel within the bound; the most accurate is {best.level} at "
            f"{best.error_ulp:.4g} ulp, {best.error_abs:.3g} absolute"
        )
    return min((render(k, target_of(isa)) for k in holds), key=lambda s: s.intrinsics)


#: SLEEF functions with a 3.5-ulp variant; the rest have only the 1-ulp one.
SLEEF_U35 = frozenset("sin cos tan exp2 exp10 log log2 atan asin acos sinh cosh tanh".split())
LIBRARY_WIDTH = {"avx2": ("d", "4"), "avx512": ("e", "8")}
#: Functions glibc's libmvec does not export.
NO_LIBRARY = frozenset({"fmod"})


def library_function(symbol: str) -> tuple[str, str, str] | None:
    """``(function, library, isa)`` of a vector math library symbol :func:`libraries` names, or ``None``."""
    return library_symbols().get(symbol)


@functools.lru_cache(maxsize=1, typed=True)
def library_symbols() -> dict[str, tuple[str, str, str]]:
    return {
        symbol: (fn, library, isa)
        for fn in functions()
        for dtype in ("f64", "f32")
        for isa in LIBRARY_WIDTH
        for level in LEVELS
        for library, symbol in libraries(fn, dtype, isa, level).items()
    }


def libraries(fn: str, dtype: str, isa: str, level: str) -> dict[str, str]:
    """The library call matching ``level`` on x86, for a loop that keeps the call: the ``{name: symbol}`` pairs."""
    name = ALIASES.get(fn, fn)
    if isa not in LIBRARY_WIDTH or name in NO_LIBRARY:
        return {}
    letter, width = LIBRARY_WIDTH[isa]
    lanes = width if dtype == "f64" else str(2 * int(width))
    suffix = "" if dtype == "f64" else "f"
    args = "vv" if name == "pow" else "v"
    accuracy = "u35" if level != "strict" and name in SLEEF_U35 else "u10"
    sleef_isa = "avx2" if isa == "avx2" else "avx512f"
    svml = {"strict": "_ha", "relaxed": ""}.get(level, "_ep")
    return {
        "libmvec": f"_ZGV{letter}N{lanes}{args}_{name}{suffix}",
        "sleef": f"Sleef_{name}{'d' if dtype == 'f64' else 'f'}{lanes}_{accuracy}{sleef_isa}",
        "svml": f"__svml_{name}{suffix}{lanes}{svml}",
    }
